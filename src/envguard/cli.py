"""Command line interface: ``envguard example`` and ``envguard check``."""

from __future__ import annotations

import argparse
import importlib
import sys
from collections.abc import Sequence
from pathlib import Path
from typing import Any, get_args, get_origin

from pydantic import BaseModel, SecretStr
from pydantic.fields import FieldInfo

from envguard.errors import EnvGuardError
from envguard.masking import is_secret_field
from envguard.profiles import get_profile
from envguard.settings import env_var_name, model_path

__all__ = ["main"]


def _import_model(path: str) -> type[BaseModel]:
    module_name, sep, attr = path.partition(":")
    if not sep:
        raise EnvGuardError(f"Invalid model path '{path}': expected 'module:ClassName'.")
    try:
        module = importlib.import_module(module_name)
    except ImportError as exc:
        raise EnvGuardError(f"Cannot import module '{module_name}': {exc}") from exc
    try:
        obj = getattr(module, attr)
    except AttributeError as exc:
        raise EnvGuardError(f"Module '{module_name}' has no attribute '{attr}'.") from exc
    if not (isinstance(obj, type) and issubclass(obj, BaseModel)):
        raise EnvGuardError(f"'{path}' is not a pydantic BaseModel subclass.")
    return obj


def _unwrap_optional(annotation: Any) -> Any:
    args = [arg for arg in get_args(annotation) if arg is not type(None)]
    if get_origin(annotation) is not None and len(args) == 1:
        return args[0]
    return annotation


def _placeholder(annotation: Any) -> str:
    resolved = _unwrap_optional(annotation)
    origin = get_origin(resolved)
    if origin in (list, set, frozenset):
        return "[]"
    if origin is tuple:
        return "()"
    if isinstance(resolved, type):
        if issubclass(resolved, bool):
            return "false"
        if issubclass(resolved, SecretStr):
            return "changeme"
        if issubclass(resolved, int):
            return "0"
        if issubclass(resolved, float):
            return "0.0"
    return ""


def _default_text(field: FieldInfo) -> str:
    default = field.get_default(call_default_factory=True)
    if default is None:
        return ""
    if isinstance(default, SecretStr):
        return "changeme"
    if isinstance(default, bool):
        return "true" if default else "false"
    return str(default)


def _render_field(
    settings_cls: type[BaseModel],
    name: str,
    field: FieldInfo,
    *,
    include_optional: bool,
) -> list[str]:
    required = field.is_required()
    if not required and not include_optional:
        return []

    env_name = env_var_name(settings_cls, name)
    secret = is_secret_field(name, field)

    labels = ["required" if required else "optional"]
    if secret:
        labels.append("secret")
    if not required:
        labels.append(f"default={_default_text(field)!r}")

    description = field.description or f"{env_name} value"
    lines = [f"# {description} [{', '.join(labels)}]"]

    if secret:
        value = "changeme"
    elif required:
        value = _placeholder(field.annotation)
    else:
        value = _default_text(field)

    lines.append(f"{env_name}={value}")
    return lines


def _generate_example(
    settings_cls: type[BaseModel],
    profile: str,
    *,
    include_optional: bool,
) -> str:
    lines = [
        "# Generated by envguard. Do not commit real secrets.",
        f"# Profile: {profile}",
        f"# Model: {model_path(settings_cls)}",
        "",
    ]
    for name, field in settings_cls.model_fields.items():
        lines.extend(_render_field(settings_cls, name, field, include_optional=include_optional))
    return "\n".join(lines).rstrip() + "\n"


def _cmd_example(args: argparse.Namespace) -> int:
    settings_cls = _import_model(args.model)
    profile = get_profile(args.profile)
    content = _generate_example(settings_cls, profile, include_optional=args.include_optional)

    output = Path(args.output)
    if output.exists() and not args.force:
        print(f"error: {output} already exists (use --force to overwrite)", file=sys.stderr)
        return 1
    output.write_text(content, encoding="utf-8")
    print(f"Wrote {output} (profile '{profile}')")
    return 0


def _cmd_check(args: argparse.Namespace) -> int:
    settings_cls = _import_model(args.model)
    settings = settings_cls()
    profile = settings.env_profile() if hasattr(settings, "env_profile") else get_profile()
    print(f"OK: {settings_cls.__name__} validated (profile '{profile}')")
    return 0


def _build_parser() -> argparse.ArgumentParser:

    parser = argparse.ArgumentParser(
        prog="envguard",
        description="Profile-aware settings and secrets management for pydantic-settings.",
    )
    parser.add_argument("--version", action="store_true", help="Print the envguard version.")
    subparsers = parser.add_subparsers(dest="command")

    example = subparsers.add_parser(
        "example", help="Generate a .env.example from a settings model."
    )
    example.add_argument("--model", required=True, help="Import path 'module:ClassName'.")
    example.add_argument(
        "--output", default=".env.example", help="Output path (default: .env.example)."
    )
    example.add_argument("--profile", default=None, help="Profile name (default: env or 'dev').")
    example.add_argument(
        "--include-optional",
        action="store_true",
        help="Also emit optional fields with their defaults.",
    )
    example.add_argument(
        "--force", action="store_true", help="Overwrite the output file if it exists."
    )
    example.set_defaults(handler=_cmd_example)

    check = subparsers.add_parser(
        "check", help="Load a settings model and report missing/invalid keys."
    )
    check.add_argument("--model", required=True, help="Import path 'module:ClassName'.")
    check.set_defaults(handler=_cmd_check)

    parser.set_defaults(handler=None)
    return parser


def main(argv: Sequence[str] | None = None) -> int:
    """Entry point for the ``envguard`` console script."""

    from envguard import __version__

    parser = _build_parser()
    args = parser.parse_args(argv)

    if args.version:
        print(f"envguard {__version__}")
        return 0

    if args.handler is None:
        parser.print_help()
        return 1

    try:
        result: int = args.handler(args)
    except EnvGuardError as exc:
        print(str(exc), file=sys.stderr)
        return 1
    return result


if __name__ == "__main__":  # pragma: no cover
    raise SystemExit(main())
